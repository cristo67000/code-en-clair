  const DICTIONNAIRES = { fr: FR, en: EN };
  let langue = 'fr';

  function remplacer(texte, variables) {
    if (!variables) return texte;
    return texte.replace(/\{(\w+)\}/g, (tout, nom) => (variables[nom] === undefined ? tout : String(variables[nom])));
  }

  /* Le texte d'une clé dans la langue courante ; à défaut, dans l'autre ;
   * à défaut encore, la clé elle-même (on la voit, on la corrige). */
  function t(cle, variables) {
    const texte = DICTIONNAIRES[langue][cle];
    if (texte !== undefined) return remplacer(texte, variables);
    const autre = DICTIONNAIRES[langue === 'fr' ? 'en' : 'fr'][cle];
    return autre !== undefined ? remplacer(autre, variables) : cle;
  }

  /* « 1 terme » / « 3 termes » : la clé finit par .1 ou .n. En français, zéro
   * est au singulier ; en anglais, il est au pluriel. */
  function plur(cle, n) {
    const singulier = langue === 'en' ? n === 1 : n <= 1;
    return t(cle + (singulier ? '.1' : '.n'), { n });
  }

  /* Pose les textes des attributs data-t… dans une portion du document. */
  function appliquer(portee) {
    const zone = portee || document;
    for (const noeud of zone.querySelectorAll('[data-t]')) noeud.textContent = t(noeud.getAttribute('data-t'));
    for (const noeud of zone.querySelectorAll('[data-t-ph]')) noeud.setAttribute('placeholder', t(noeud.getAttribute('data-t-ph')));
    for (const noeud of zone.querySelectorAll('[data-t-aria]')) noeud.setAttribute('aria-label', t(noeud.getAttribute('data-t-aria')));
    for (const noeud of zone.querySelectorAll('[data-t-titre]')) noeud.setAttribute('title', t(noeud.getAttribute('data-t-titre')));
  }

  function definir(nouvelle) {
    langue = nouvelle === 'en' ? 'en' : 'fr';
    document.documentElement.lang = langue;
    appliquer();
    document.dispatchEvent(new CustomEvent('langue-changee'));
  }

  racine.I18n = {
    t, plur, appliquer, definir,
    get langue() { return langue; },
    dictionnaires: DICTIONNAIRES,
  };

